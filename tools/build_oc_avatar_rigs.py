def check_source(path, expected):
    if hashlib.sha256(path.read_bytes()).hexdigest() != expected:
        raise ValueError(f"Wrong source for registered landmarks: {path.name}")


def bind_pair(portraits, sheets, output):
    for case, spec in PORTRAITS.items():
        check_source(portraits / spec["filename"], spec["sha256"])
        check_source(sheets / CASES[case]["filename"], spec["sheet_sha256"])
    output.mkdir(parents=True, exist_ok=False)
    for case, spec in PORTRAITS.items():
        with Image.open(portraits / spec["filename"]) as source:
            master = ImageOps.pad(source.convert("RGB"), SIZE, method=Image.Resampling.LANCZOS)
        donor = cut(sheet_portrait(sheets, case), mask(CASES[case]["mouth"]))
        donor = donor.crop(donor.getbbox()).rotate(spec["roll"], Image.Resampling.BICUBIC, expand=True)
        left, top, right, bottom = spec["open_box"]
        opening = Image.new("RGBA", SIZE)
        opening.paste(
            donor.crop(donor.getbbox()).resize((right - left, bottom - top), Image.Resampling.LANCZOS),
            (left, top),
        )
        model = bind_portrait(master, spec, open_layer=opening, closed_layer=cut(master, mask(spec["mouth"])))
        model.save(output / case, "大肥鱼 OC · " + ("mature" if case == "regular" else "Q"))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    for argument in ("portraits", "sheets", "output"):
        parser.add_argument(argument, type=Path)
    bind_pair(**vars(parser.parse_args()))
